#!/usr/bin/env python3
"""Writes infra/imports.tf from the real IDs of the resources in the three CloudFormation stacks.

Run it BEFORE the stacks are deleted: afterwards the IDs are only in the console.
Run it through imports.sh, which calls the AWS CLI and passes the results in.

Besides imports.tf it writes infra/migrate/old-roles.txt: the IAM roles CloudFormation created
with generated names. Terraform creates its own, explicitly named roles instead of importing
those (see docs/lab7-migration.md), so the old ones are deleted at the end by finish.sh.
"""

import json
import os
import sys
from pathlib import Path

PROJECT = os.environ.get("PROJECT_NAME") or os.environ.get("APP_NAME") or "meetings"
INFRA = Path(__file__).resolve().parent.parent


def physical_ids(stack):
    """Reads the stack's resources from the JSON that imports.sh saved (it calls the AWS CLI)."""
    path = Path(os.environ["DUMP_DIR"]) / f"{stack}.json"
    if not path.exists():
        sys.exit(f"Missing {path}; run this through infra/migrate/imports.sh")
    summaries = json.loads(path.read_text(encoding="utf-8-sig"))["StackResourceSummaries"]
    return {r["LogicalResourceId"]: r["PhysicalResourceId"] for r in summaries if r["ResourceStatus"] != "DELETE_COMPLETE"}


account = os.environ["ACCOUNT_ID"]
imports = []  # (terraform address, id, comment)
old_roles = []

# ------------------------------------------------------------------------------- auth
auth = physical_ids(f"{PROJECT}-auth")
pool = auth["UserPool"]
imports += [
    ("aws_cognito_user_pool.main", pool, "every account that signed up lives here"),
    ("aws_cognito_user_pool_domain.main", auth["UserPoolDomain"], ""),
    ("aws_cognito_user_pool_client.web", f"{pool}/{auth['UserPoolClient']}", ""),
    ("aws_cognito_managed_login_branding.main", f"{pool},{auth['ManagedLoginBranding'].split('|')[-1]}", ""),
]
if "GoogleIdentityProvider" in auth:
    imports.append(("aws_cognito_identity_provider.google[0]", f"{pool}:Google", "set google_client_id in terraform.tfvars"))
else:
    print("Google sign-in is not in the auth stack: keep google_client_id = \"\" in terraform.tfvars")

# ---------------------------------------------------------------------------- reports
reports = physical_ids(f"{PROJECT}-reports")
bucket = reports["ReportsBucket"]
schedule = reports["WeeklyReportSchedule"]
imports += [
    ("aws_vpc_endpoint.s3", reports["S3Endpoint"], ""),
    ("aws_s3_bucket.reports", bucket, "every report lives here"),
    ("aws_s3_bucket_lifecycle_configuration.reports", bucket, "was inside the bucket resource"),
    ("aws_s3_bucket_notification.reports", bucket, "was inside the bucket resource"),
    ("aws_sqs_queue.report_requests_dlq", reports["ReportRequestsDLQ"], ""),
    ("aws_sqs_queue.report_requests", reports["ReportRequestsQueue"], ""),
    ("aws_scheduler_schedule.weekly_report", schedule if "/" in schedule else f"default/{schedule}", ""),
    ("aws_cloudwatch_log_group.report_builder", reports["ReportBuilderLogGroup"], ""),
    ("aws_lambda_function.report_builder", reports["ReportBuilderFunction"], ""),
    ("aws_lambda_event_source_mapping.report_builder", reports["ReportBuilderEventSource"], ""),
    ("aws_cloudwatch_log_group.report_mailer", reports["ReportMailerLogGroup"], ""),
    ("aws_lambda_function.report_mailer", reports["ReportMailerFunction"], ""),
]
old_roles += [reports["SchedulerRole"], reports["ReportBuilderRole"], reports["ReportMailerRole"]]

# --------------------------------------------------------------------------------- ai
ai = physical_ids(f"{PROJECT}-ai")
imports += [
    ("aws_cloudwatch_log_group.agenda_parser", ai["ParserLogGroup"], ""),
    ("aws_lambda_function.agenda_parser", ai["ParserFunction"], ""),
    ("aws_lambda_function_url.agenda_parser", ai["ParserFunction"], "the import id is the function name"),
    ("aws_budgets_budget.monthly", f"{account}:{PROJECT}-monthly", ""),
]
old_roles.append(ai["ParserRole"])

lines = [
    "# Generated by infra/migrate/make_imports.py from the CloudFormation stacks. Delete this file",
    "# after the migration: an import block only matters once, and `terraform plan` must say",
    "# \"No changes\" without it.",
    "",
]
for address, import_id, comment in imports:
    if comment:
        lines.append(f"# {comment}")
    lines += ["import {", f"  to = {address}", f'  id = "{import_id}"', "}", ""]
(INFRA / "imports.tf").write_text("\n".join(lines))
(INFRA / "migrate" / "old-roles.txt").write_text("\n".join(old_roles) + "\n")

print(f"infra/imports.tf: {len(imports)} import blocks")
print(f"infra/migrate/old-roles.txt: {len(old_roles)} IAM roles to delete after the apply")
